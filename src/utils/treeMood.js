/** 统计某段日期内经历了几个节气 */
export function countJieqiBetween(startDateStr, endDateStr) {
  const start = new Date(startDateStr)
  const end = new Date(endDateStr || new Date().toISOString().substring(0, 10))
  return Object.keys(JIEQI).filter(d => {
    const dt = new Date(d)
    return dt >= start && dt <= end
  }).length
}

/**
 * 树的今日心情
 * 根据时间、季节、传感器数据生成一句拟人化的状态文案
 */

export function getTreeMood(hour, month, temp = null, humidity = null) {
  // 传感器异常状态优先
  if (temp !== null && temp > 32) return '今天温度有点高，我把叶子微微卷起来，等待傍晚的凉风。'
  if (temp !== null && temp < 5)  return '气温很低，我已把能量收回到根里，静静等待春天。'
  if (humidity !== null && humidity > 85) return '今天雨水很足，我喝得饱饱的，叶子格外翠绿。'
  if (humidity !== null && humidity < 20) return '空气有些干燥，叶尖有点渴了，希望今晚能下场雨。'

  const spring = month >= 3 && month <= 5
  const summer = month >= 6 && month <= 8
  const autumn = month >= 9 && month <= 11
  const winter = !spring && !summer && !autumn

  const dawn     = hour >= 5  && hour < 7
  const morning  = hour >= 7  && hour < 11
  const noon     = hour >= 11 && hour < 14
  const afternoon= hour >= 14 && hour < 18
  const evening  = hour >= 18 && hour < 21
  // 夜间: 其余

  if (spring) {
    if (dawn)      return '清晨的露水还挂在叶尖，今天又是新的一天。'
    if (morning)   return '春光正好，嫩芽已经探出头来了。'
    if (noon)      return '春日阳光正暖，茶农的脚步从山下传来了。'
    if (afternoon) return '下午有微风，茶园里飘着淡淡的清香。'
    if (evening)   return '暮色降临，今天又长出了新的一片叶子。'
    return '夜里的山很安静，嫩芽在月光下悄悄生长。'
  }
  if (summer) {
    if (dawn)      return '天刚亮，露水润湿了叶片，今天会是热烈的一天。'
    if (morning)   return '早晨还凉快，趁这时多晒点阳光。'
    if (noon)      return '正午的阳光很烈，我把叶面转向，避开最毒的一面。'
    if (afternoon) return '暑气渐消，山风快来吧。'
    if (evening)   return '夜里的山风很凉，可以好好休息了。'
    return '深夜的山南很安静，虫鸣声伴着入眠。'
  }
  if (autumn) {
    if (dawn)      return '秋天的黎明，山谷里有薄薄的晨雾。'
    if (morning)   return '秋高气爽，今天的光线格外透亮。'
    if (noon)      return '午后山谷有轻雾弥漫，秋意正浓。'
    if (afternoon) return '下午的光斜斜打在叶片上，留下今天最好看的影子。'
    if (evening)   return '落日把茶园染成了暖橙色，很美。'
    return '秋夜清冷，月亮挂得很高，星星很多。'
  }
  // winter
  if (dawn)      return '冬天的黎明来得很晚，天还黑着，我在静静等待。'
  if (morning)   return '冬日晨光不暖，但我在根里积蓄着力量。'
  if (noon)      return '冬日正午还算暖和，我把叶子对准了太阳。'
  if (afternoon) return '寒意渐重，我把根扎得更深了，等待春天。'
  if (evening)   return '冬夜来得很早，山南已经归于沉寂。'
  return '大雪封山的夜里，我在土里沉沉睡着。'
}

